package mart;

public class Buyer {
	
	
	private String customer;
	private int wallet;
	private int point;
	
	
	public Buyer() {
		this.customer = customer;
		this.wallet = wallet;
		this.point = point;
	}
	
	public int getWallet() {
		return this.wallet;
	}
	
	public int getPoint() {
		return this.point;
	}
	
	
	
	
	
	
	
	
	
	

}
